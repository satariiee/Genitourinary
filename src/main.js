function navigate(page, data) {
  app.innerHTML = '';
  switch (page) {
    case 'login':
      renderLogin(app, navigate);
      break;
    case 'dashboard':
      renderDashboard(app, navigate);
      break;
    case 'select':
      renderSelectDifficulty(app, navigate);
      break;
    case 'quiz':
      renderQuiz(app, navigate, data);
      break;
    case 'results':
      renderResults(app, navigate, data);
      break;
    default:
      renderLogin(app, navigate);
  }
}

// initial route
const savedUser = sessionStorage.getItem('gu_username');
